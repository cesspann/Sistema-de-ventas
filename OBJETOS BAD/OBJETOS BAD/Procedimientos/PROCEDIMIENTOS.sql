    INNER JOIN CATEGORIA C ON C.ID_CATEGORIA = P.ID_CATEGORIA
    INNER JOIN INVENTARIO I ON I.ID_PRODUCTO = P.ID_PRODUCTO
    WHERE I.ID_SUCURSAL = V_ID_SUCURSAL
    AND P.ESTADO_PRODUCTO = 'Inactivo'
    ORDER BY P.ID_PRODUCTO ASC;

