    -- Reporte de ventas realizadas por vendedor
    SELECT V.ID_EMPLEADO, E.NOMBRE_EMPLEADO, F.ID_SUCURSAL, S.NOMBRE_SUCURSAL, COUNT(F.ID_FACTURA) AS TOTAL_FACTURAS, COALESCE(SUM(F.MONTO_TOTAL), 0) AS TOTAL_VENTAS
