DROP PROCEDURE SP_DEFINIR_ROL_USUARIO%%
CREATE PROCEDURE SP_DEFINIR_ROL_USUARIO(
    IN NOMUSUARIO VARCHAR(50),
    OUT ROL INTEGER 
)
BLOQUE : BEGIN

    DECLARE V_TIPO VARCHAR(20) DEFAULT NULL;
    DECLARE V_CONTEO INTEGER DEFAULT 0;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        SET ROL = -1;
    END;
    
    IF NOMUSUARIO IS NULL OR TRIM(NOMUSUARIO) = '' THEN
        SET ROL = -2;
        LEAVE BLOQUE;
    END IF;

    SELECT E.TIPO_EMPLEADO 
    INTO V_TIPO
    FROM USUARIO U
    JOIN EMPLEADO E ON U.ID_USUARIO = E.ID_USUARIO
    WHERE U.NOMBRE_USUARIO = TRIM(NOMUSUARIO);

    IF V_TIPO IS NULL THEN
        SET ROL = -3;
        LEAVE BLOQUE;
    END IF;

    IF V_TIPO = 'Supervisor' THEN
        SET ROL = 3;
        LEAVE BLOQUE;
    END IF;

    SELECT COUNT(*)
    INTO V_CONTEO
    FROM USUARIO U 
    JOIN EMPLEADO E ON U.ID_USUARIO = E.ID_USUARIO 
    JOIN CAJERO C ON E.ID_EMPLEADO = C.ID_EMPLEADO
    WHERE U.NOMBRE_USUARIO = TRIM(NOMUSUARIO);

    IF V_CONTEO = 1 THEN
        SET ROL = 1;
        LEAVE BLOQUE;
    END IF;

    SELECT COUNT(*)
    INTO V_CONTEO
    FROM USUARIO U 
    JOIN EMPLEADO E ON U.ID_USUARIO = E.ID_USUARIO 
    JOIN VENDEDOR V ON E.ID_EMPLEADO = V.ID_EMPLEADO
    WHERE U.NOMBRE_USUARIO = TRIM(NOMUSUARIO);
    
    IF V_CONTEO = 1 THEN
        SET ROL = 2;
        LEAVE BLOQUE;
    END IF;

    SET ROL = -3;

END%%


